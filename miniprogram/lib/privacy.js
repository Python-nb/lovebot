// Only platform-confirmed authorization may unlock BLE. No local "consent" flag.
function authorize(api) {
  if (typeof api.requirePrivacyAuthorize !== 'function')
    return Promise.reject(new Error('当前微信版本不支持隐私授权，请升级微信后再使用此功能。'));
  return new Promise((resolve, reject) =>
    api.requirePrivacyAuthorize({
      success: resolve,
      fail: () =>
        reject(new Error('未完成隐私授权，无法使用此功能。请阅读用户隐私保护指引后重试。')),
    }),
  );
}
function openContract(api) {
  if (typeof api.openPrivacyContract !== 'function')
    return Promise.reject(new Error('请升级微信后查看用户隐私保护指引。'));
  return new Promise((resolve, reject) =>
    api.openPrivacyContract({
      success: resolve,
      fail: () => reject(new Error('隐私保护指引暂不可用，请稍后重试或联系开发者。')),
    }),
  );
}
